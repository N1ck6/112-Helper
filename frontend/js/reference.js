  function wireReference(root) {
    const input = root.querySelector("#ref-search");
    const blocks = Array.from(root.querySelectorAll("details[data-ref]"));
    const initiallyOpen = blocks.map((d) => d.open);
    input.addEventListener("input", () => {
      const q = input.value.trim().toLowerCase();
      let shown = 0;
      blocks.forEach((d, i) => {
        const hit = !q || d.textContent.toLowerCase().indexOf(q) !== -1;
        d.hidden = !hit;
        d.open = q ? hit : initiallyOpen[i];
        if (hit) shown++;
      });
      root.querySelector("#ref-empty").hidden = shown > 0;
    });
    root.addEventListener("click", (e) => {
      const btn = e.target.closest("[data-dial]");
      if (btn) document.dispatchEvent(new CustomEvent("dds:dial", { detail: { number: btn.dataset.dial } }));
    });
  }

