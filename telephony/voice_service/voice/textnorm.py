"""Подготовка текста к синтезу: сокращения из карточек 112 -> полные слова.

Адреса в карточках пишутся сокращённо («ул. Ясный проезд, д. 10»), а Piper
читает сокращения буквально. Правила — только однозначные сокращения адресов.
"""

import re

_RULES = [
    (r"\bул\.\s*", "улица "),
    (r"\bд\.\s*(?=\d)", "дом "),
    (r"\bкв\.\s*(?=\d)", "квартира "),
    (r"\bкорп\.\s*(?=\d)", "корпус "),
    (r"\bстр\.\s*(?=\d)", "строение "),
    (r"\bпод\.\s*(?=\d)", "подъезд "),
    (r"\bэт\.\s*(?=\d)", "этаж "),
    (r"\bпр-т\b\.?", "проспект"),
    (r"\bпр-д\b\.?", "проезд"),
    (r"\bб-р\b\.?", "бульвар"),
    (r"\bпер\.\s*", "переулок "),
    (r"\bш\.\s*", "шоссе "),
    (r"\bпл\.\s*", "площадь "),
    (r"\bнаб\.\s*", "набережная "),
    (r"\bг\.\s*(?=[А-ЯЁ])", "город "),
    (r"\bр-н\b\.?", "район"),
]
_COMPILED = [(re.compile(p, re.IGNORECASE), r) for p, r in _RULES]


def normalize_for_tts(text: str) -> str:
    for pattern, repl in _COMPILED:
        text = pattern.sub(repl, text)
    text = re.sub(r"\s+([,.;:!?])", r"\1", text)   # «улица , 62» -> «улица, 62»
    return re.sub(r"\s{2,}", " ", text).strip()
